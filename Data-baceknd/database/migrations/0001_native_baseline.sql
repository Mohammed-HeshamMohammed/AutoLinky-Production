CREATE FUNCTION public.match_opportunities(p_user uuid, p_since timestamp with time zone DEFAULT (now() - '30 days'::interval), p_limit integer DEFAULT 20, p_offset integer DEFAULT 0, p_work_modes text[] DEFAULT NULL::text[], p_apply text[] DEFAULT NULL::text[], p_sources text[] DEFAULT NULL::text[], p_min_score integer DEFAULT 0) RETURNS TABLE(id uuid, source text, title text, company text, city text, country text, country_code text, work_mode text, level text, employment_type text, field text, role text, skills text[], apply_methods text[], language text, snippet text, url text, posted_at timestamp with time zone, score integer, reasons jsonb)
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public', 'extensions', 'pg_temp'
    AS $$
DECLARE
    u      user_profiles%ROWTYPE;
    st     match_cache_state%ROWTYPE;
    meta   match_cache_meta%ROWTYPE;
    prof   jsonb;
    wm     text[];
    lim    integer := LEAST(GREATEST(p_limit, 1), 100);
    off    integer := GREATEST(p_offset, 0);
    days   integer := GREATEST(current_date - (p_since AT TIME ZONE 'UTC')::date, 1);
    ids    uuid[];
    kmin   numeric;
    bmax   numeric;
    exact  boolean;
BEGIN
    SELECT * INTO u FROM user_profiles up WHERE up.user_id = p_user;
    IF NOT FOUND THEN
        RETURN;
    END IF;
    prof := scope_profile(to_jsonb(u));
    wm := scope_work_modes(u.search_scope, p_work_modes);

    SELECT * INTO meta FROM match_cache_meta x WHERE x.id;
    SELECT * INTO st FROM match_cache_state s WHERE s.user_id = p_user;
    IF NOT FOUND OR st.dirty
       OR (st.stats_version < meta.stats_version AND meta.stats_at < now() - interval '1 hour') THEN
        PERFORM match_cache_rebuild(p_user, false);
        SELECT * INTO st FROM match_cache_state s WHERE s.user_id = p_user;
    END IF;
    IF st.read_at < now() - interval '1 hour' THEN
        UPDATE match_cache_state s SET read_at = now() WHERE s.user_id = p_user;
    END IF;

    -- the page, ranked as match_profile ranks (score + up to 5 points for fresh jobs, then newest, then id)
    SELECT array_agg(c.opportunity_id ORDER BY c.k DESC, c.posted_at DESC, c.opportunity_id DESC), min(c.k)
    INTO ids, kmin
    FROM (
        SELECT m.opportunity_id, o.posted_at,
               m.total + 5 * GREATEST(0, 1 - (current_date - (o.posted_at AT TIME ZONE 'UTC')::date)::numeric / days) AS k
        FROM match_cache m
        JOIN opportunities o ON o.id = m.opportunity_id
        WHERE m.user_id = p_user
          AND o.status = 'active'
          AND o.posted_at >= p_since
          AND m.total >= p_min_score
          AND (wm IS NULL OR o.work_mode = ANY(wm))
          AND (p_apply IS NULL OR o.apply_methods && p_apply)
          AND (p_sources IS NULL OR o.source = ANY(p_sources))
        ORDER BY k DESC, o.posted_at DESC, m.opportunity_id DESC
        LIMIT lim OFFSET off
    ) c;
    -- the most a job left out can get for freshness (5, more only for a date ahead of the server's)
    SELECT 5 * GREATEST(1, 1 - (current_date - (max(o.posted_at) AT TIME ZONE 'UTC')::date)::numeric / days)
    INTO bmax FROM opportunities o;

    exact := COALESCE(st.user_id IS NOT NULL AND NOT st.dirty
                      AND NOT EXISTS (SELECT 1 FROM match_cache_queue q WHERE q.queued_at < now() - interval '10 minutes')
                      AND (st.complete
                           OR p_min_score > st.floor                         -- nothing left out reaches the minimum
                           OR (cardinality(ids) = lim AND kmin > st.floor + bmax)),   -- nor ranks on this page
                      false);
    -- which way this call went, for the checks (scripts/loadtest/compare_match_cache.sh, the tests)
    PERFORM set_config('autolinky.match_source', CASE WHEN exact THEN 'cache' ELSE 'live' END, true);
    IF NOT exact THEN
        RETURN QUERY SELECT * FROM match_profile(prof, p_since, lim, off, wm, p_apply, p_sources, p_min_score);
        RETURN;
    END IF;
    IF ids IS NULL THEN
        RETURN;
    END IF;
    RETURN QUERY
        SELECT r.* FROM match_profile(prof, p_since, lim, 0, wm, p_apply, p_sources, p_min_score, ids) r
        ORDER BY array_position(ids, r.id);
END;
$$;

CREATE FUNCTION public.match_profile(p_profile jsonb, p_since timestamp with time zone DEFAULT (now() - '30 days'::interval), p_limit integer DEFAULT 20, p_offset integer DEFAULT 0, p_work_modes text[] DEFAULT NULL::text[], p_apply text[] DEFAULT NULL::text[], p_sources text[] DEFAULT NULL::text[], p_min_score integer DEFAULT 0, p_ids uuid[] DEFAULT NULL::uuid[]) RETURNS TABLE(id uuid, source text, title text, company text, city text, country text, country_code text, work_mode text, level text, employment_type text, field text, role text, skills text[], apply_methods text[], language text, snippet text, url text, posted_at timestamp with time zone, score integer, reasons jsonb)
    LANGUAGE sql STABLE
    SET search_path TO 'pg_catalog', 'public', 'pg_temp'
    SET work_mem TO '32MB'
    AS $$
    -- Set-based: the candidate jobs are found with joins (no per-row subqueries), every (job, skill) weight is
    -- computed in one pass and summed per job, and the lists of shared / missing skills are built only for the
    -- page that is returned.
    WITH consts AS (
        -- the weight of a typical skill a job asks for: a job's skill weight counts at least ~3 of them
        SELECT COALESCE((SELECT sum(jobs * spec) / NULLIF(sum(jobs), 0) FROM role_skill_stats), 1.5)::numeric AS med,
               COALESCE((SELECT array_agg(slug) FROM skills WHERE skill_group = 'languages'), '{}') AS langs,
               COALESCE((SELECT array_agg(skill) FROM skill_stats WHERE spec_any >= 1.5), '{}') AS specific
    ),
    raw AS (
        SELECT ARRAY(SELECT e FROM jsonb_array_elements_text(CASE WHEN jsonb_typeof(p_profile->'target_roles') = 'array'
                                 THEN p_profile->'target_roles' ELSE '[]' END) WITH ORDINALITY AS t(e, i) ORDER BY i)
                   AS target_roles,
               ARRAY(SELECT jsonb_array_elements_text(CASE WHEN jsonb_typeof(p_profile->'target_fields') = 'array'
                                 THEN p_profile->'target_fields' ELSE '[]' END)) AS target_fields,
               ARRAY(SELECT jsonb_array_elements_text(CASE WHEN jsonb_typeof(p_profile->'skills') = 'array'
                                 THEN p_profile->'skills' ELSE '[]' END)) AS skills,
               ARRAY(SELECT jsonb_array_elements_text(CASE WHEN jsonb_typeof(p_profile->'countries') = 'array'
                                 THEN p_profile->'countries' ELSE '[]' END)) AS countries,
               ARRAY(SELECT jsonb_array_elements_text(CASE WHEN jsonb_typeof(p_profile->'languages') = 'array'
                                 THEN p_profile->'languages' ELSE '[]' END)) AS languages,
               COALESCE((p_profile->>'remote_ok')::boolean, true) AS remote_ok,
               ARRAY(SELECT lower(t) FROM jsonb_array_elements_text(
                         CASE WHEN jsonb_typeof(p_profile->'search_titles') = 'array'
                              THEN p_profile->'search_titles' ELSE '[]' END) t
                     UNION SELECT lower(p_profile->>'headline') WHERE coalesce(p_profile->>'headline', '') <> '')
                   AS titles,
               p_profile->>'level' AS level,
               (p_profile->>'years_experience')::integer AS years_experience
        WHERE p_profile IS NOT NULL AND jsonb_typeof(p_profile) = 'object'
    ),
    prof AS (
        SELECT u.*,
               COALESCE(u.level, CASE WHEN u.years_experience IS NULL THEN NULL
                                      WHEN u.years_experience <= 2 THEN 'junior'
                                      WHEN u.years_experience <= 5 THEN 'mid'
                                      ELSE 'senior' END) AS level_x,
               ARRAY(SELECT x FROM (SELECT unnest(u.skills) AS x
                                    UNION
                                    SELECT si.implied FROM skill_implications si WHERE si.skill = ANY(u.skills)) t
                     WHERE NOT (x = ANY(k.langs))) AS skills_x
        FROM raw u CROSS JOIN consts k
    ),
    tfields_pos AS (
        SELECT unnest(p.target_fields) AS f, 1 AS pos FROM prof p
        UNION ALL
        SELECT r.field, array_position(p.target_roles, r.slug) FROM prof p JOIN job_roles r ON r.slug = ANY(p.target_roles)
    ),
    tfields AS (SELECT f, min(pos) AS pos FROM tfields_pos GROUP BY f),
    related AS (
        SELECT fr.field_b AS f, max(fr.weight) AS w
        FROM field_relations fr JOIN tfields t ON t.f = fr.field_a
        WHERE fr.field_b NOT IN (SELECT f FROM tfields)
        GROUP BY fr.field_b
    ),
    aff AS (
        SELECT ra.role_b AS role,
               max(CASE array_position(p.target_roles, ra.role_a) WHEN 1 THEN 1.0 WHEN 2 THEN 0.9 ELSE 0.8 END
                   * ra.weight) AS w
        FROM role_affinity ra CROSS JOIN prof p
        WHERE ra.role_a = ANY(p.target_roles)
        GROUP BY ra.role_b
    ),
    cand AS (
        SELECT o.id, o.source, o.title, o.company, o.city, o.country, o.country_code, o.work_mode, o.level,
               o.employment_type, o.field, o.role, o.role_confidence, o.skills, o.title_skills, o.req_skills,
               o.pref_skills, o.requirements_read, o.min_years, o.apply_methods, o.language, o.snippet, o.url,
               o.posted_at,
               p.target_roles AS u_roles, p.skills_x AS u_skills, p.level_x AS u_level, p.years_experience AS u_years,
               p.titles AS u_titles, p.countries AS u_countries, p.remote_ok AS u_remote_ok,
               t.pos AS field_pos, r.w AS rel_w, a.w AS aff_w,
               (SELECT max(extensions.similarity(lower(o.title), x)) FROM unnest(p.titles) x) AS title_sim
        FROM opportunities o
        CROSS JOIN prof p
        CROSS JOIN consts k
        LEFT JOIN tfields t ON t.f = o.field
        LEFT JOIN related r ON r.f = o.field
        LEFT JOIN aff a ON a.role = o.role
        WHERE o.status = 'active'
          AND (p_ids IS NULL OR o.id IN (SELECT unnest(p_ids)))   -- a hashed lookup, not a scan of the array
          AND o.posted_at >= p_since
          AND (o.role = ANY(p.target_roles) OR t.f IS NOT NULL OR r.f IS NOT NULL OR a.role IS NOT NULL
               -- no role / field link: real skill overlap needed (cheap array overlap test first)
               OR (o.skills && p.skills_x
                   AND ((cardinality(p.target_roles) = 0
                         AND cardinality(ARRAY(SELECT unnest(o.skills) INTERSECT SELECT unnest(p.skills_x))) >= 2)
                        OR cardinality(ARRAY(SELECT unnest(o.skills) INTERSECT SELECT unnest(p.skills_x)
                                             INTERSECT SELECT unnest(k.specific))) >= 3)))
          -- a job whose country is not known (a post that never says where) is no job "in Egypt": it matches
          -- users who look everywhere, and users open to remote work when it is remote (Step 8i)
          AND (cardinality(p.countries) = 0 OR o.country_code = ANY(p.countries)
               OR (o.work_mode = 'remote' AND p.remote_ok))
          AND (cardinality(p.languages) = 0 OR o.language = ANY(p.languages))
          AND (p_work_modes IS NULL OR o.work_mode = ANY(p_work_modes))
          AND (p_apply IS NULL OR o.apply_methods && p_apply)
          AND (p_sources IS NULL OR o.source = ANY(p_sources))
    ),
    -- every (candidate job, skill): how much it weighs (role importance x how the ad asks for it x title)
    cs AS (
        SELECT c.id, s.skill,
               COALESCE(rs.spec, st.spec_any, 1.0)
               * CASE WHEN NOT c.requirements_read THEN 0.8
                      WHEN s.skill = ANY(c.req_skills) THEN 1.0
                      WHEN s.skill = ANY(c.pref_skills) THEN 0.5
                      ELSE 0.35 END
               * CASE WHEN s.skill = ANY(c.title_skills) THEN 1.5 ELSE 1 END AS w,
               (s.skill = ANY(c.req_skills)) AS req,
               (s.skill = ANY(c.u_skills)) AS hit
        FROM cand c
        CROSS JOIN LATERAL unnest(c.skills) AS s(skill)
        CROSS JOIN consts k
        LEFT JOIN role_skill_stats rs ON rs.role = c.role AND rs.skill = s.skill
        LEFT JOIN skill_stats st ON st.skill = s.skill
        WHERE NOT (s.skill = ANY(k.langs))
    ),
    agg AS (
        SELECT cs.id, sum(cs.w) AS tot_w, COALESCE(sum(cs.w) FILTER (WHERE cs.hit), 0) AS sh_w
        FROM cs GROUP BY cs.id
    ),
    scored AS (
        SELECT c.*, COALESCE(g.tot_w, 0) AS tot_w, COALESCE(g.sh_w, 0) AS sh_w,
               (CASE WHEN c.role = ANY(c.u_roles)
                          THEN CASE array_position(c.u_roles, c.role) WHEN 1 THEN 1.0 WHEN 2 THEN 0.9 ELSE 0.8 END
                     ELSE GREATEST(COALESCE(c.aff_w, 0),
                                   CASE WHEN c.field_pos IS NOT NULL
                                        THEN 0.5 * CASE c.field_pos WHEN 1 THEN 1.0 WHEN 2 THEN 0.8 ELSE 0.6 END
                                        ELSE 0.5 * COALESCE(c.rel_w, 0) END)
                END)
               * (CASE WHEN c.role_confidence >= 0.7 THEN 1.0 ELSE 0.6 END)
               -- how close the job's title is to the titles the user is after: 0.7 (unlike) .. 1.0 (alike, trigram
               -- similarity 0.8+); neutral when the profile has no titles
               * (CASE WHEN cardinality(c.u_titles) = 0 THEN 1.0
                       ELSE 0.7 + 0.3 * LEAST(1, GREATEST(0, (COALESCE(c.title_sim, 0) - 0.3) / 0.5)) END) AS s_role,
               array_position(ARRAY['intern', 'junior', 'mid', 'senior', 'manager'], c.level) AS j_lvl,
               array_position(ARRAY['intern', 'junior', 'mid', 'senior', 'manager'], c.u_level) AS u_lvl
        FROM cand c LEFT JOIN agg g ON g.id = c.id
    ),
    parts AS (
        SELECT s.*,
               CASE WHEN s.tot_w = 0 OR cardinality(s.u_skills) = 0 THEN 0.4
                    ELSE 0.6 * LEAST(1.0, s.sh_w / GREATEST(s.tot_w, k.med * 3))
                       + 0.4 * LEAST(1.0, ln(1 + s.sh_w) / ln(1 + k.med * 4)) END AS s_skill,
               CASE WHEN s.min_years IS NOT NULL AND s.u_years IS NOT NULL THEN
                        -- the ad says how many years: compare them (and still: far above the job costs a little)
                        LEAST(CASE WHEN s.min_years - s.u_years <= 0 THEN 1.0
                                   WHEN s.min_years - s.u_years = 1 THEN 0.92
                                   WHEN s.min_years - s.u_years = 2 THEN 0.8
                                   WHEN s.min_years - s.u_years <= 4 THEN 0.6
                                   ELSE 0.45 END,
                              CASE WHEN s.j_lvl IS NOT NULL AND s.u_lvl IS NOT NULL AND s.u_lvl - s.j_lvl >= 2
                                   THEN 0.75 ELSE 1.0 END)
                    WHEN s.j_lvl IS NULL OR s.u_lvl IS NULL THEN 0.92
                    ELSE CASE s.j_lvl - s.u_lvl
                             WHEN 0 THEN 1.0 WHEN 1 THEN 0.9 WHEN 2 THEN 0.6 WHEN -1 THEN 0.95 WHEN -2 THEN 0.75
                             ELSE CASE WHEN s.j_lvl > s.u_lvl THEN 0.4 ELSE 0.55 END
                         END END AS s_level,
               CASE WHEN cardinality(s.u_countries) = 0 OR s.country_code = ANY(s.u_countries)
                         OR (s.work_mode = 'remote' AND s.u_remote_ok) THEN 1.0
                    ELSE 0.6 END AS s_loc
        FROM scored s CROSS JOIN consts k
    ),
    final AS (
        SELECT p.*,
               round(CASE WHEN LEAST(p.s_role, p.s_skill, p.s_level, p.s_loc) >= 0.9
                               THEN 100 * (0.50 * p.s_role + 0.38 * p.s_skill + 0.12 * p.s_loc) * p.s_level
                          ELSE LEAST(97, 100 * (0.50 * p.s_role + 0.38 * p.s_skill + 0.12 * p.s_loc) * p.s_level)
                     END::numeric)::integer AS total
        FROM parts p
    ),
    page AS (
        SELECT f.*,
               -- the percent is fit only; ranking adds up to 5 points for fresh jobs, counted in whole days so the
               -- order stays the same between the pages of one day (the app pages with an offset)
               row_number() OVER (ORDER BY f.total + 5 * GREATEST(0, 1 - (current_date - (f.posted_at AT TIME ZONE 'UTC')::date)::numeric
                                                    / GREATEST(current_date - (p_since AT TIME ZONE 'UTC')::date, 1)) DESC,
                                           f.posted_at DESC, f.id DESC) AS rk
        FROM final f
        WHERE f.total >= p_min_score
        ORDER BY rk
        LIMIT LEAST(GREATEST(p_limit, 1), 2000) OFFSET GREATEST(p_offset, 0)   -- 2000: the cache's builds (the API asks 50 at most)
    ),
    -- the shared and missing skills of the page's jobs, each list built in one pass over cs (before: two
    -- subqueries per job, each scanning all of cs: 40 scans of ~130k rows for a page of 20)
    page_skills AS (
        SELECT x.id, jsonb_agg(x.skill ORDER BY x.w DESC, x.skill) AS skills
        FROM cs x
        WHERE x.hit AND x.id IN (SELECT id FROM page)
        GROUP BY x.id
    ),
    page_missing AS (
        SELECT y.id, jsonb_agg(y.skill ORDER BY y.req DESC, y.w DESC, y.skill) AS missing
        FROM (SELECT x.id, x.skill, x.req, x.w,
                     row_number() OVER (PARTITION BY x.id ORDER BY x.req DESC, x.w DESC, x.skill) AS n
              FROM cs x
              WHERE NOT x.hit AND x.id IN (SELECT id FROM page)) y
        WHERE y.n <= 3
        GROUP BY y.id
    )
    SELECT f.id, f.source, f.title, f.company, f.city, f.country, f.country_code, f.work_mode, f.level,
           f.employment_type, f.field, f.role, f.skills, f.apply_methods, f.language, f.snippet, f.url, f.posted_at,
           f.total,
           jsonb_build_object(
               'role', CASE WHEN f.role = ANY(f.u_roles) THEN 'same_role'
                            WHEN COALESCE(f.aff_w, 0) >= 0.5 THEN 'similar_role'
                            WHEN f.field_pos IS NOT NULL THEN 'same_field'
                            WHEN f.rel_w IS NOT NULL THEN 'related_field'
                            ELSE 'skills_only' END,
               'skills', COALESCE(ps.skills, '[]'),
               'missing', COALESCE(pm.missing, '[]'),
               'level', CASE WHEN f.j_lvl IS NULL OR f.u_lvl IS NULL THEN 'unknown'
                             WHEN f.j_lvl = f.u_lvl THEN 'match'
                             WHEN abs(f.j_lvl - f.u_lvl) = 1 THEN 'close'
                             ELSE 'far' END,
               'location', CASE WHEN f.country_code = ANY(f.u_countries) THEN 'country'
                                WHEN f.work_mode = 'remote' THEN 'remote'
                                WHEN cardinality(f.u_countries) = 0 THEN 'anywhere'
                                ELSE 'unknown' END,
               'parts', jsonb_build_object('role', round(f.s_role::numeric, 2), 'skills', round(f.s_skill::numeric, 2),
                                           'level', round(f.s_level::numeric, 2), 'location', round(f.s_loc::numeric, 2))
           )
    FROM page f
    LEFT JOIN page_skills ps ON ps.id = f.id
    LEFT JOIN page_missing pm ON pm.id = f.id
    ORDER BY f.rk;
$$;

CREATE FUNCTION public.opportunity_facets(p_since timestamp with time zone DEFAULT (now() - '30 days'::interval)) RETURNS jsonb
    LANGUAGE sql STABLE
    SET search_path TO 'pg_catalog', 'public', 'pg_temp'
    AS $$
    WITH a AS (SELECT * FROM opportunities WHERE status = 'active' AND posted_at >= p_since)
    SELECT jsonb_build_object(
        'total',         (SELECT count(*) FROM a),
        'fields',        (SELECT COALESCE(jsonb_agg(jsonb_build_object('value', field, 'count', n) ORDER BY n DESC), '[]')
                          FROM (SELECT field, count(*) n FROM a GROUP BY field) x),
        'roles',         (SELECT COALESCE(jsonb_agg(jsonb_build_object('value', role, 'count', n) ORDER BY n DESC), '[]')
                          FROM (SELECT role, count(*) n FROM a WHERE role IS NOT NULL GROUP BY role) x),
        'countries',     (SELECT COALESCE(jsonb_agg(jsonb_build_object('value', country_code, 'name', country, 'count', n)
                                                    ORDER BY n DESC), '[]')
                          FROM (SELECT country_code, max(country) country, count(*) n FROM a
                                WHERE country_code IS NOT NULL GROUP BY country_code) x),
        'levels',        (SELECT COALESCE(jsonb_agg(jsonb_build_object('value', level, 'count', n) ORDER BY n DESC), '[]')
                          FROM (SELECT level, count(*) n FROM a GROUP BY level) x),
        'work_modes',    (SELECT COALESCE(jsonb_agg(jsonb_build_object('value', work_mode, 'count', n) ORDER BY n DESC), '[]')
                          FROM (SELECT work_mode, count(*) n FROM a GROUP BY work_mode) x),
        'apply_methods', (SELECT COALESCE(jsonb_agg(jsonb_build_object('value', m, 'count', n) ORDER BY n DESC), '[]')
                          FROM (SELECT m, count(*) n FROM a, unnest(apply_methods) m GROUP BY m) x),
        'sources',       (SELECT COALESCE(jsonb_agg(jsonb_build_object('value', source, 'count', n) ORDER BY n DESC), '[]')
                          FROM (SELECT source, count(*) n FROM a GROUP BY source) x),
        'languages',     (SELECT COALESCE(jsonb_agg(jsonb_build_object('value', language, 'count', n) ORDER BY n DESC), '[]')
                          FROM (SELECT language, count(*) n FROM a GROUP BY language) x)
    );
$$;

CREATE FUNCTION public.opportunity_feed(p_q text DEFAULT NULL::text, p_fields text[] DEFAULT NULL::text[], p_roles text[] DEFAULT NULL::text[], p_skills text[] DEFAULT NULL::text[], p_countries text[] DEFAULT NULL::text[], p_work_modes text[] DEFAULT NULL::text[], p_levels text[] DEFAULT NULL::text[], p_apply text[] DEFAULT NULL::text[], p_sources text[] DEFAULT NULL::text[], p_languages text[] DEFAULT NULL::text[], p_since timestamp with time zone DEFAULT NULL::timestamp with time zone, p_after_at timestamp with time zone DEFAULT NULL::timestamp with time zone, p_after_id uuid DEFAULT NULL::uuid, p_limit integer DEFAULT 20) RETURNS TABLE(id uuid, source text, title text, company text, city text, country text, country_code text, work_mode text, level text, employment_type text, field text, role text, skills text[], apply_methods text[], language text, snippet text, url text, posted_at timestamp with time zone)
    LANGUAGE sql STABLE
    SET search_path TO 'pg_catalog', 'public', 'extensions', 'pg_temp'
    AS $$
    SELECT o.id, o.source, o.title, o.company, o.city, o.country, o.country_code, o.work_mode, o.level,
           o.employment_type, o.field, o.role, o.skills, o.apply_methods, o.language, o.snippet, o.url, o.posted_at
    FROM opportunities o
    WHERE o.status = 'active'
      AND (p_since IS NULL OR o.posted_at >= p_since)
      AND (p_q IS NULL OR o.search_blob ILIKE
           '%' || replace(replace(replace(p_q, '\', '\\'), '%', '\%'), '_', '\_') || '%')
      AND (p_fields IS NULL OR o.field = ANY(p_fields))
      AND (p_roles IS NULL OR o.role = ANY(p_roles))
      AND (p_skills IS NULL OR o.skills && p_skills)
      AND (p_countries IS NULL OR o.country_code = ANY(p_countries))
      AND (p_work_modes IS NULL OR o.work_mode = ANY(p_work_modes))
      AND (p_levels IS NULL OR o.level = ANY(p_levels))
      AND (p_apply IS NULL OR o.apply_methods && p_apply)
      AND (p_sources IS NULL OR o.source = ANY(p_sources))
      AND (p_languages IS NULL OR o.language = ANY(p_languages))
      AND (p_after_at IS NULL OR (o.posted_at, o.id) < (p_after_at, p_after_id))
    ORDER BY o.posted_at DESC, o.id DESC
    LIMIT LEAST(GREATEST(p_limit, 1), 100);
$$;

