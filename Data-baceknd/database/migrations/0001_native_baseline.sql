CREATE FUNCTION public.match_cache_rebuild(p_user uuid, p_force boolean DEFAULT true) RETURNS integer
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public', 'extensions', 'pg_temp'
    AS $$
DECLARE
    meta   match_cache_meta%ROWTYPE;
    st     match_cache_state%ROWTYPE;
    u      user_profiles%ROWTYPE;
    days   integer := GREATEST(current_date - (match_cache_since() AT TIME ZONE 'UTC')::date, 1);
    oldest date;
    n      integer;
    kmin   numeric;
BEGIN
    PERFORM pg_advisory_xact_lock(hashtextextended('match_cache:' || p_user::text, 0));   -- one build at a time
    SELECT * INTO meta FROM match_cache_meta x WHERE x.id;   -- first: statistics newer than this make it stale again
    SELECT * INTO st FROM match_cache_state s WHERE s.user_id = p_user;
    IF NOT p_force AND FOUND AND NOT st.dirty AND st.stats_version >= meta.stats_version THEN
        RETURN -1;
    END IF;
    SELECT * INTO u FROM user_profiles up WHERE up.user_id = p_user;
    IF NOT FOUND THEN
        RETURN 0;
    END IF;
    INSERT INTO match_cache_state (user_id) VALUES (p_user) ON CONFLICT (user_id) DO NOTHING;
    DELETE FROM match_cache c WHERE c.user_id = p_user;
    SELECT (min(o.posted_at) AT TIME ZONE 'UTC')::date INTO oldest FROM opportunities o;
    WITH best AS (
        SELECT m.id, m.score AS total,
               m.score + 5 * GREATEST(0, 1 - (current_date - (m.posted_at AT TIME ZONE 'UTC')::date)::numeric / days) AS k
        FROM match_profile(scope_profile(to_jsonb(u)), match_cache_since(), meta.size, 0,
                           scope_work_modes(u.search_scope, NULL), NULL, NULL, 0) m
    ), ins AS (
        INSERT INTO match_cache (user_id, opportunity_id, total)
        SELECT p_user, b.id, b.total FROM best b
        RETURNING 1
    )
    SELECT (SELECT count(*) FROM ins), (SELECT min(b.k) FROM best b) INTO n, kmin;
    -- a job left out ranks at most kmin; its bonus is at least the oldest job's, so it scores at most:
    UPDATE match_cache_state s
    SET built_at = now(), complete = n < meta.size, stats_version = meta.stats_version,
        floor = COALESCE(kmin - 5 * GREATEST(0, 1 - (current_date - oldest)::numeric / days), 0),
        dirty = s.marks <> COALESCE(st.marks, 0)   -- marked again while this ran: it saw the old profile
    WHERE s.user_id = p_user;
    RETURN n;
END;
$$;

CREATE FUNCTION public.match_cache_rebuild_stale(p_max_seconds integer DEFAULT 5, p_idle_days integer DEFAULT 3) RETURNS integer
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public', 'extensions', 'pg_temp'
    AS $$
DECLARE
    started timestamptz := clock_timestamp();
    r       record;
    n       integer := 0;
BEGIN
    DELETE FROM match_cache_state s WHERE s.read_at < now() - make_interval(days => p_idle_days);
    FOR r IN SELECT s.user_id FROM match_cache_state s, match_cache_meta m
             WHERE m.id AND (s.dirty OR s.stats_version < m.stats_version)
             ORDER BY s.dirty DESC, s.read_at DESC
    LOOP
        EXIT WHEN clock_timestamp() - started > make_interval(secs => p_max_seconds);
        CONTINUE WHEN NOT pg_try_advisory_xact_lock(hashtextextended('match_cache:' || r.user_id::text, 0));
        IF match_cache_rebuild(r.user_id, false) >= 0 THEN
            n := n + 1;
        END IF;
    END LOOP;
    RETURN n;
END;
$$;

