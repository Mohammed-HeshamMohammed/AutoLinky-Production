CREATE FUNCTION public.search_title_key(p_title text) RETURNS text
    LANGUAGE plpgsql IMMUTABLE PARALLEL SAFE
    SET search_path TO 'pg_catalog', 'public', 'pg_temp'
    AS $_$
DECLARE
    t text := lower(normalize(COALESCE(p_title, ''), NFKC));
BEGIN
    IF t ~ '@|https?:|www\.' THEN
        RETURN NULL;
    END IF;
    t := regexp_replace(t, '\([^)]*\)|\[[^]]*\]', ' ', 'g');               -- (CCNP), [Remote]
    t := regexp_replace(t, '\s+[-–—]\s+.*$|\s*[|:•·].*$', '');              -- 'x - backend', 'x | y', 'x: y'
    t := btrim(regexp_replace(t, '\s+', ' ', 'g'));
    t := regexp_replace(t, '^(?:(?:senior|sr|junior|jr|mid-level|mid level|entry-level|entry level)\.?(?:\s+|$))+', '');
    t := regexp_replace(t, '^[\s,;/\\_*''"-]+|[\s.,;/\\_*''"-]+$', '', 'g');  -- a leading '.' stays: '.net developer'
    IF char_length(t) NOT BETWEEN 2 AND 60
       OR array_length(string_to_array(t, ' '), 1) > 6
       OR t !~ '[a-zà-ɏ؀-ۿ]' THEN
        RETURN NULL;
    END IF;
    RETURN t;
END;
$_$;

CREATE FUNCTION public.search_title_keys(p_titles text[]) RETURNS text[]
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    SET search_path TO 'pg_catalog', 'public', 'pg_temp'
    AS $$
    SELECT COALESCE(array_agg(k ORDER BY first), '{}')
    FROM (SELECT k, min(u.n) AS first
          FROM unnest(COALESCE(p_titles, '{}')) WITH ORDINALITY AS u(title, n)
          CROSS JOIN LATERAL search_title_key(u.title) AS k
          WHERE k IS NOT NULL
          GROUP BY k
          ORDER BY first
          LIMIT 8) AS keyed;
$$;


