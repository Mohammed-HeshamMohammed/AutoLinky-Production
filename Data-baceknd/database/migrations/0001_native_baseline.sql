CREATE FUNCTION public.pending_requirements_wanted(p_limit integer DEFAULT 300, p_scan integer DEFAULT 1000) RETURNS TABLE(source text, source_ref text, title text, body text, content_hash text)
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public', 'extensions', 'pg_temp'
    AS $$
DECLARE
    -- a skipped job is looked at again once a profile or the matching's statistics changed after it was skipped
    changed timestamptz := GREATEST(
        (SELECT max(GREATEST(u.updated_at, u.created_at)) FROM user_profiles u),
        (SELECT m.stats_at FROM match_cache_meta m WHERE m.id));
    ids    uuid[];
    wanted uuid[];
BEGIN
    CREATE TEMP TABLE IF NOT EXISTS requirements_look ON COMMIT DROP AS
        SELECT * FROM requirements_pending_all() WITH NO DATA;
    TRUNCATE requirements_look;
    INSERT INTO requirements_look
    SELECT a.*
    FROM requirements_pending_all() a
    LEFT JOIN requirements_skipped s ON s.opportunity_id = a.id
    WHERE s.opportunity_id IS NULL OR s.content_hash <> a.content_hash OR s.checked_at < changed
    ORDER BY a.posted_at DESC
    LIMIT LEAST(GREATEST(p_scan, 1), 1000);       -- below match_profile's 2000: every candidate among them comes back
    SELECT array_agg(l.id) INTO ids FROM requirements_look l;
    IF ids IS NULL THEN
        RETURN;
    END IF;
    SELECT array_agg(DISTINCT m.id) INTO wanted
    FROM user_profiles u
    CROSS JOIN LATERAL match_profile(scope_profile(to_jsonb(u)), match_cache_since(), 2000, 0,
                                     scope_work_modes(u.search_scope, NULL), NULL, NULL, 0, ids) m;
    wanted := COALESCE(wanted, '{}');
    INSERT INTO requirements_skipped (opportunity_id, content_hash, checked_at)
    SELECT l.id, l.content_hash, now() FROM requirements_look l WHERE NOT (l.id = ANY(wanted))
    ON CONFLICT (opportunity_id) DO UPDATE SET content_hash = EXCLUDED.content_hash, checked_at = EXCLUDED.checked_at;
    RETURN QUERY
        SELECT l.source, l.source_ref, l.title, l.body, l.content_hash
        FROM requirements_look l
        WHERE l.id = ANY(wanted)
        ORDER BY l.posted_at DESC
        LIMIT LEAST(GREATEST(p_limit, 1), 2000);
END;
$$;

