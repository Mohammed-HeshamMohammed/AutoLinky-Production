CREATE FUNCTION public.user_profiles_search_titles_changed() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public', 'pg_temp'
    AS $$
DECLARE
    v_keys text[] := '{}';
    v_key  text;
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.search_keys IS NOT DISTINCT FROM NEW.search_keys
       AND OLD.search_scope IS NOT DISTINCT FROM NEW.search_scope THEN
        RETURN NULL;
    END IF;
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        v_keys := v_keys || OLD.search_keys;
    END IF;
    IF TG_OP IN ('UPDATE', 'INSERT') THEN
        v_keys := v_keys || NEW.search_keys;
    END IF;
    IF cardinality(v_keys) = 0 THEN
        RETURN NULL;
    END IF;
    PERFORM pg_advisory_xact_lock(hashtext('autolinky.search_titles'));
    FOR v_key IN SELECT DISTINCT k FROM unnest(v_keys) AS k ORDER BY k LOOP
        PERFORM recount_search_title(v_key);
    END LOOP;
    RETURN NULL;
END;
$$;

