CREATE FUNCTION public.admin_overview(p_days integer DEFAULT 30) RETURNS jsonb
    LANGUAGE sql STABLE
    SET search_path TO 'pg_catalog', 'public', 'pg_temp'
    AS $$
    WITH bounds AS (
        SELECT greatest(7, least(coalesce(p_days, 30), 365)) AS days,
               (now() AT TIME ZONE 'Africa/Cairo')::date AS today,
               ((now() AT TIME ZONE 'Africa/Cairo')::date)::timestamp AT TIME ZONE 'Africa/Cairo' AS today_start
    ),
    days AS (
        SELECT generate_series(b.today - (b.days - 1), b.today, interval '1 day')::date AS day FROM bounds b
    ),
    since AS (
        SELECT (min(d.day))::timestamp AT TIME ZONE 'Africa/Cairo' AS t FROM days d
    ),
    signups AS (
        SELECT (u.created_at AT TIME ZONE 'Africa/Cairo')::date AS day, count(*) AS n
        FROM app_users u, since s WHERE u.created_at >= s.t GROUP BY 1
    ),
    downloads AS (
        SELECT (d.created_at AT TIME ZONE 'Africa/Cairo')::date AS day, count(*) AS n
        FROM app_downloads d, since s
        WHERE d.kind = 'download' AND NOT d.is_bot AND d.created_at >= s.t GROUP BY 1
    ),
    mails AS (
        SELECT (a.sent_at AT TIME ZONE 'Africa/Cairo')::date AS day, count(*) AS n
        FROM applications a, since s
        WHERE a.method = 'email' AND a.status = 'sent' AND a.sent_at >= s.t GROUP BY 1
    )
    SELECT jsonb_build_object(
        'now', now(),
        'users', (SELECT jsonb_build_object(
            'total', count(*),
            'today', count(*) FILTER (WHERE u.created_at >= b.today_start),
            'last_7d', count(*) FILTER (WHERE u.created_at > now() - interval '7 days'),
            'last_30d', count(*) FILTER (WHERE u.created_at > now() - interval '30 days'),
            'active_24h', count(*) FILTER (WHERE u.last_seen_at > now() - interval '24 hours'),
            'active_7d', count(*) FILTER (WHERE u.last_seen_at > now() - interval '7 days'),
            'active_30d', count(*) FILTER (WHERE u.last_seen_at > now() - interval '30 days'),
            'blocked', count(*) FILTER (WHERE u.status = 'blocked'))
            FROM app_users u, bounds b),
        'downloads', (SELECT jsonb_build_object(
            'total', count(*),
            'today', count(*) FILTER (WHERE d.created_at >= b.today_start),
            'last_7d', count(*) FILTER (WHERE d.created_at > now() - interval '7 days'),
            'last_30d', count(*) FILTER (WHERE d.created_at > now() - interval '30 days'),
            'visitors_30d', count(DISTINCT d.visitor) FILTER (WHERE d.created_at > now() - interval '30 days'),
            'last_at', max(d.created_at))
            FROM app_downloads d, bounds b WHERE d.kind = 'download' AND NOT d.is_bot),
        'emails', (SELECT jsonb_build_object(
            'total', count(*) FILTER (WHERE a.status = 'sent'),
            'today', count(*) FILTER (WHERE a.status = 'sent' AND a.sent_at >= b.today_start),
            'last_7d', count(*) FILTER (WHERE a.status = 'sent' AND a.sent_at > now() - interval '7 days'),
            'last_30d', count(*) FILTER (WHERE a.status = 'sent' AND a.sent_at > now() - interval '30 days'),
            'auto_30d', count(*) FILTER (WHERE a.status = 'sent' AND a.auto
                                             AND a.sent_at > now() - interval '30 days'),
            'failed_30d', count(*) FILTER (WHERE a.status = 'failed' AND a.updated_at > now() - interval '30 days'),
            'senders_30d', count(DISTINCT a.user_id) FILTER (WHERE a.status = 'sent'
                                                                 AND a.sent_at > now() - interval '30 days'))
            FROM applications a, bounds b WHERE a.method = 'email'),
        'plans', jsonb_build_object(
            'pro', (SELECT count(*) FROM subscriptions s
                    WHERE s.starts_at <= now() AND (s.ends_at IS NULL OR s.ends_at > now())),
            'pro_ending_7d', (SELECT count(*) FROM subscriptions s
                              WHERE s.starts_at <= now() AND s.ends_at > now()
                                AND s.ends_at <= now() + interval '7 days'),
            'unlimited', (SELECT count(*) FROM user_limits l WHERE l.unlimited),
            'custom', (SELECT count(*) FROM user_limits l
                       WHERE l.free_emails IS NOT NULL OR l.unlimited OR l.daily_limit IS NOT NULL
                          OR l.daily_unlimited)),
        'jobs', (SELECT jsonb_build_object(
            'total', count(*),
            'today', count(*) FILTER (WHERE o.created_at >= b.today_start),
            'last_at', max(o.created_at))
            FROM opportunities o, bounds b),
        'auto_apply', jsonb_build_object(
            'on', (SELECT count(*) FROM auto_apply x WHERE x.enabled),
            'gmail_ok', (SELECT count(*) FROM mail_accounts m WHERE m.status = 'ok'),
            'gmail_invalid', (SELECT count(*) FROM mail_accounts m WHERE m.status = 'invalid'),
            'with_cv', (SELECT count(*) FROM user_cvs c)),
