CREATE FUNCTION public.match_cache_apply_queue(p_max integer DEFAULT 1000, p_bulk integer DEFAULT 3000) RETURNS integer
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public', 'extensions', 'pg_temp'
    AS $$
DECLARE
    meta    match_cache_meta%ROWTYPE;
    st      match_cache_state%ROWTYPE;
    ids     uuid[];
    r       record;
    n       integer;
    dropped numeric;
BEGIN
    IF (SELECT count(*) FROM (SELECT 1 FROM match_cache_queue LIMIT p_bulk + 1) q) > p_bulk THEN
        DELETE FROM match_cache_queue WHERE true;   -- first: a build that started before it is left dirty below
        UPDATE match_cache_state s SET dirty = true, marks = s.marks + 1 WHERE true;
        RETURN -1;
    END IF;
    WITH taken AS (
        DELETE FROM match_cache_queue q
        WHERE q.opportunity_id IN (SELECT x.opportunity_id FROM match_cache_queue x ORDER BY x.queued_at
                                   LIMIT LEAST(p_max, 2000) FOR UPDATE SKIP LOCKED)
        RETURNING q.opportunity_id
    )
    SELECT array_agg(t.opportunity_id) INTO ids FROM taken t;
    IF ids IS NULL THEN
        RETURN 0;
    END IF;
    SELECT * INTO meta FROM match_cache_meta x WHERE x.id;
    FOR r IN SELECT s.user_id FROM match_cache_state s ORDER BY s.user_id LOOP
        -- after the lock, the cache as its last build left it (a build that started before these jobs were saved
        -- has finished); a dirty one is skipped: its next build sees them
        PERFORM pg_advisory_xact_lock(hashtextextended('match_cache:' || r.user_id::text, 0));
        SELECT * INTO st FROM match_cache_state s WHERE s.user_id = r.user_id;
        CONTINUE WHEN NOT FOUND OR st.dirty;
        DELETE FROM match_cache c WHERE c.user_id = r.user_id AND c.opportunity_id = ANY(ids);
        INSERT INTO match_cache (user_id, opportunity_id, total)
        SELECT r.user_id, m.id, m.score
        FROM user_profiles up
        CROSS JOIN LATERAL match_profile(scope_profile(to_jsonb(up)), match_cache_since(), cardinality(ids), 0,
                                         scope_work_modes(up.search_scope, NULL), NULL, NULL, 0, ids) m
        WHERE up.user_id = r.user_id
          AND (st.complete OR m.score > st.floor)      -- at or under the floor it stays out: it cannot rank in
        ON CONFLICT (user_id, opportunity_id) DO UPDATE SET total = EXCLUDED.total;
        -- back to the size: the lowest go, and the floor rises to the best of them
        SELECT count(*) INTO n FROM match_cache c WHERE c.user_id = r.user_id;
        IF n > meta.size + 200 THEN
            WITH gone AS (
                DELETE FROM match_cache c
                WHERE c.user_id = r.user_id
                  AND c.opportunity_id IN (SELECT x.opportunity_id FROM match_cache x WHERE x.user_id = r.user_id
                                           ORDER BY x.total, x.opportunity_id LIMIT n - meta.size)
                RETURNING c.total
            )
            SELECT max(g.total) INTO dropped FROM gone g;
            UPDATE match_cache_state s
            SET floor = CASE WHEN s.complete THEN dropped ELSE GREATEST(s.floor, dropped) END, complete = false
            WHERE s.user_id = r.user_id;
        END IF;
    END LOOP;
    RETURN cardinality(ids);
END;
$$;

