CREATE FUNCTION public.purge_old_data(p_days integer DEFAULT 14) RETURNS jsonb
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public', 'pg_temp'
    AS $$
DECLARE
    cutoff    timestamptz := now() - make_interval(days => GREATEST(COALESCE(p_days, 14), 7));
    n_opp     integer;
    n_req     integer;
    n_posts   integer;
    n_jobs    integer;
    n_more    integer;
    n_verdict integer;
    n_letter  integer;
BEGIN
    -- jobs posted before the cutoff, with what was built from them (one statement: nothing is left behind for the
    -- enricher to rebuild). Applications stay; an e-mail going out right now keeps its job until the next run.
    WITH gone AS (
        DELETE FROM opportunities o
        WHERE o.posted_at < cutoff
          AND NOT EXISTS (SELECT 1 FROM applications a WHERE a.opportunity_id = o.id AND a.status = 'sending')
        RETURNING o.source, o.source_ref
    ), req AS (
        DELETE FROM job_requirements r USING gone g
        WHERE r.source = g.source AND r.source_ref = g.source_ref
        RETURNING 1
    ), posts AS (
        DELETE FROM hiring_posts p USING gone g
        WHERE g.source = 'post' AND p.id::text = g.source_ref
        RETURNING 1
    ), ljobs AS (
        DELETE FROM linkedin_jobs j USING gone g
        WHERE g.source = 'linkedin_job' AND j.job_id = g.source_ref
        RETURNING 1
    )
    SELECT (SELECT count(*) FROM gone), (SELECT count(*) FROM req), (SELECT count(*) FROM posts),
           (SELECT count(*) FROM ljobs)
    INTO n_opp, n_req, n_posts, n_jobs;

    -- raw rows found before the cutoff that never became an opportunity
    DELETE FROM hiring_posts p
    WHERE p.created_at < cutoff
      AND NOT EXISTS (SELECT 1 FROM opportunities o WHERE o.source = 'post' AND o.source_ref = p.id::text);
    GET DIAGNOSTICS n_more = ROW_COUNT;
    n_posts := n_posts + n_more;

    DELETE FROM linkedin_jobs j
    WHERE j.first_seen_at < cutoff
      AND NOT EXISTS (SELECT 1 FROM opportunities o WHERE o.source = 'linkedin_job' AND o.source_ref = j.job_id);
    GET DIAGNOSTICS n_more = ROW_COUNT;
    n_jobs := n_jobs + n_more;

    DELETE FROM job_requirements r
    WHERE r.created_at < cutoff
      AND NOT EXISTS (SELECT 1 FROM opportunities o WHERE o.source = r.source AND o.source_ref = r.source_ref);
    GET DIAGNOSTICS n_more = ROW_COUNT;
    n_req := n_req + n_more;

    -- the AI's verdicts on posts that old (searches only read the last week's posts)
    DELETE FROM post_verdicts v WHERE v.created_at < cutoff;
    GET DIAGNOSTICS n_verdict = ROW_COUNT;

    -- letters: sent (kept in applications.letter), for a job that is gone, or a preview older than the cutoff
    DELETE FROM cover_letters c
    WHERE c.created_at < cutoff
       OR NOT EXISTS (SELECT 1 FROM opportunities o WHERE o.id = c.opportunity_id)
       OR EXISTS (SELECT 1 FROM applications a
                  WHERE a.user_id = c.user_id AND a.opportunity_id = c.opportunity_id AND a.status = 'sent');
    GET DIAGNOSTICS n_letter = ROW_COUNT;

    RETURN jsonb_build_object('opportunities', n_opp, 'hiring_posts', n_posts, 'linkedin_jobs', n_jobs,
                              'job_requirements', n_req, 'post_verdicts', n_verdict, 'cover_letters', n_letter);
END;
$$;

CREATE FUNCTION public.recount_search_title(p_key text) RETURNS void
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public', 'pg_temp'
    AS $$
DECLARE
    v_users  integer;
    v_scopes text[];
BEGIN
    SELECT count(*), COALESCE(array_agg(DISTINCT COALESCE(p.search_scope, 'worldwide')), '{}')
    INTO v_users, v_scopes
    FROM user_profiles p
    JOIN app_users a ON a.id = p.user_id AND a.status = 'active'
    WHERE p.search_keys @> ARRAY[p_key];
    IF v_users > 0 THEN
        INSERT INTO search_titles AS s (title, canonical, users, scopes)
        VALUES (p_key, p_key, v_users, v_scopes)
        ON CONFLICT (title) DO UPDATE SET users = EXCLUDED.users, scopes = EXCLUDED.scopes
        WHERE (s.users, s.scopes) IS DISTINCT FROM (EXCLUDED.users, EXCLUDED.scopes);
    ELSE
        UPDATE search_titles SET users = 0, scopes = '{}'
        WHERE title = p_key AND (users <> 0 OR scopes <> '{}');
    END IF;
END;
$$;

CREATE FUNCTION public.refresh_opportunity_status() RETURNS integer
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public', 'pg_temp'
    AS $$
DECLARE
    seen integer;
    expired integer;
BEGIN
    UPDATE opportunities o
       SET last_seen_at = j.last_seen_at, status = 'active', updated_at = now()
      FROM linkedin_jobs j
     WHERE o.source = 'linkedin_job' AND o.source_ref = j.job_id
       AND j.last_seen_at > COALESCE(o.last_seen_at, '-infinity'::timestamptz)
       AND j.last_seen_at > now() - interval '21 days';
    GET DIAGNOSTICS seen = ROW_COUNT;

    UPDATE opportunities
       SET status = 'expired', updated_at = now()
     WHERE status = 'active'
       AND ((source = 'linkedin_job' AND COALESCE(last_seen_at, posted_at) < now() - interval '21 days')
         OR (source = 'post' AND posted_at < now() - interval '45 days'));
    GET DIAGNOSTICS expired = ROW_COUNT;
    RETURN seen + expired;
END;
$$;

CREATE FUNCTION public.refresh_role_affinity() RETURNS integer
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public', 'pg_temp'
    AS $$
DECLARE
    n integer;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM skill_stats) THEN
        RETURN 0;
    END IF;
    DELETE FROM role_affinity WHERE true;   -- a WHERE: Supabase refuses a bare DELETE through the API (safeupdate)
    INSERT INTO role_affinity (role_a, role_b, weight)
    WITH base AS (
        SELECT o.role, o.skills FROM opportunities o
        WHERE o.status = 'active' AND o.role IS NOT NULL AND o.role_confidence >= 0.7 AND cardinality(o.skills) > 0
    ),
    rc AS (SELECT role, count(*) AS n FROM base GROUP BY role HAVING count(*) >= 8),
    v AS (
        SELECT b.role, s AS skill, (count(*)::numeric / rc.n) * st.weight AS x
        FROM base b
        JOIN rc ON rc.role = b.role
        CROSS JOIN LATERAL unnest(b.skills) s
        JOIN skill_stats st ON st.skill = s
        JOIN skills sk ON sk.slug = s AND sk.skill_group <> 'languages'
        GROUP BY b.role, s, rc.n, st.weight
    ),
    nrm AS (SELECT role, sqrt(sum(x * x)) AS r FROM v GROUP BY role),
    dots AS (
        SELECT a.role AS ra, b.role AS rb, sum(a.x * b.x) AS d
        FROM v a JOIN v b ON a.skill = b.skill AND a.role <> b.role
        GROUP BY a.role, b.role
    ),
    sim AS (
        SELECT dots.ra, dots.rb, dots.d / (na.r * nb.r) AS cos
        FROM dots JOIN nrm na ON na.role = dots.ra JOIN nrm nb ON nb.role = dots.rb
    ),
    ranked AS (
        SELECT ra, rb, cos, row_number() OVER (PARTITION BY ra ORDER BY cos DESC, rb) AS rk
        FROM sim WHERE cos >= 0.55
    )
    SELECT ra, rb, LEAST(0.9, cos * cos)::real FROM ranked WHERE rk <= 8;
    GET DIAGNOSTICS n = ROW_COUNT;
    RETURN n;
END;
$$;

CREATE FUNCTION public.refresh_role_skill_stats() RETURNS integer
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public', 'pg_temp'
    AS $$
DECLARE
    n integer;
BEGIN
    DELETE FROM role_skill_stats WHERE true;   -- a WHERE: Supabase refuses a bare DELETE through the API (safeupdate)
    INSERT INTO role_skill_stats (role, skill, jobs, share, spec, updated_at)
    WITH base AS (
        SELECT o.role, o.skills, o.req_skills, o.pref_skills, o.requirements_read,
               power(0.5, GREATEST(0, extract(epoch FROM (now() - o.posted_at)) / 86400.0) / 90.0) AS w
        FROM opportunities o
        WHERE o.status = 'active' AND o.role IS NOT NULL AND o.role_confidence >= 0.7
    ),
    rn AS (SELECT role, sum(w) AS n, count(*) AS cnt FROM base GROUP BY role),
    big AS (SELECT count(*)::numeric AS roles FROM rn WHERE cnt >= 8),
    sig AS (
        SELECT b.role, s AS skill,
               sum(b.w * CASE WHEN NOT b.requirements_read THEN 0.6
                              WHEN s = ANY(b.req_skills) THEN 1.0
                              WHEN s = ANY(b.pref_skills) THEN 0.5
                              ELSE 0.25 END) AS jobs
        FROM base b CROSS JOIN LATERAL unnest(b.skills) s
        WHERE s NOT IN (SELECT slug FROM skills WHERE skill_group = 'languages')
          AND s IN (SELECT slug FROM skills)
        GROUP BY b.role, s
    ),
    macro AS (
        SELECT sig.skill, sum(sig.jobs / rn.n) / NULLIF((SELECT roles FROM big), 0) AS p
        FROM sig JOIN rn ON rn.role = sig.role AND rn.cnt >= 8
        GROUP BY sig.skill
    )
    SELECT sig.role, sig.skill, sig.jobs,
           (sig.jobs + 10 * GREATEST(COALESCE(m.p, 0), 0.001)) / (rn.n + 10),
           LEAST(3, GREATEST(0.25, ln(1 + ((sig.jobs + 10 * GREATEST(COALESCE(m.p, 0), 0.001)) / (rn.n + 10))
                                         / GREATEST(COALESCE(m.p, 0), 0.001)))),
           now()
    FROM sig JOIN rn ON rn.role = sig.role
    LEFT JOIN macro m ON m.skill = sig.skill;
    GET DIAGNOSTICS n = ROW_COUNT;

    -- for jobs whose role is unknown: a typical share (0.15) against the cross-profession share
    UPDATE skill_stats st
       SET share_macro = COALESCE(x.p, 0),
           spec_any = LEAST(3, GREATEST(0.25, ln(1 + 0.15 / GREATEST(COALESCE(x.p, 0), 0.001))))
      FROM (SELECT sk.slug,
                   (SELECT sum(rs.share) FROM role_skill_stats rs WHERE rs.skill = sk.slug)
                   / NULLIF((SELECT count(DISTINCT rs.role) FROM role_skill_stats rs), 0) AS p
              FROM skills sk) x
     WHERE x.slug = st.skill;
    RETURN n;
END;
$$;

CREATE FUNCTION public.refresh_search_titles() RETURNS integer
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public', 'pg_temp'
    AS $$
DECLARE
    v_titles integer;
BEGIN
    PERFORM pg_advisory_xact_lock(hashtext('autolinky.search_titles'));
    WITH wanted AS (
        SELECT k AS title, count(*)::integer AS users,
               array_agg(DISTINCT COALESCE(p.search_scope, 'worldwide')) AS scopes
        FROM user_profiles p
        JOIN app_users a ON a.id = p.user_id AND a.status = 'active'
        CROSS JOIN LATERAL unnest(p.search_keys) AS k
        GROUP BY k
    ), upserted AS (
        INSERT INTO search_titles AS s (title, canonical, users, scopes)
        SELECT title, title, users, scopes FROM wanted ORDER BY title
        ON CONFLICT (title) DO UPDATE SET users = EXCLUDED.users, scopes = EXCLUDED.scopes
        WHERE (s.users, s.scopes) IS DISTINCT FROM (EXCLUDED.users, EXCLUDED.scopes)
        RETURNING 1
    )
    UPDATE search_titles s SET users = 0, scopes = '{}'
    WHERE (s.users <> 0 OR s.scopes <> '{}') AND s.title NOT IN (SELECT title FROM wanted);
    SELECT count(*) INTO v_titles FROM search_titles WHERE users > 0;
    RETURN v_titles;
END;
$$;

CREATE FUNCTION public.refresh_skill_stats() RETURNS integer
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public', 'pg_temp'
    AS $$
DECLARE
    total bigint;
    n integer;
BEGIN
    SELECT count(*) INTO total FROM opportunities WHERE status = 'active' AND cardinality(skills) > 0;
    IF total < 50 THEN
        RETURN 0;
    END IF;
    INSERT INTO skill_stats (skill, df, weight, updated_at)
    SELECT sk.slug, COALESCE(d.c, 0),
           CASE WHEN d.c IS NULL THEN 4.0
                ELSE GREATEST(0.5, LEAST(4.0, ln(total::numeric / d.c))) END,
           now()
    FROM skills sk
    LEFT JOIN (SELECT s AS skill, count(*) AS c
               FROM opportunities o CROSS JOIN LATERAL unnest(o.skills) s
               WHERE o.status = 'active' GROUP BY s) d ON d.skill = sk.slug
    WHERE sk.active
    ON CONFLICT (skill) DO UPDATE
        SET df = EXCLUDED.df, weight = EXCLUDED.weight, updated_at = EXCLUDED.updated_at;
    GET DIAGNOSTICS n = ROW_COUNT;
    DELETE FROM skill_stats WHERE skill NOT IN (SELECT slug FROM skills WHERE active);
    RETURN n;
END;
$$;

CREATE FUNCTION public.requirements_pending_all() RETURNS TABLE(id uuid, source text, source_ref text, title text, body text, content_hash text, posted_at timestamp with time zone)
