                       'day', d.day, 'signups', coalesce(su.n, 0), 'downloads', coalesce(dl.n, 0),
                       'emails', coalesce(m.n, 0)) ORDER BY d.day), '[]'::jsonb)
                   FROM days d
                   LEFT JOIN signups su ON su.day = d.day
                   LEFT JOIN downloads dl ON dl.day = d.day
                   LEFT JOIN mails m ON m.day = d.day)
    );
$$;

CREATE FUNCTION public.admin_users(p_search text DEFAULT NULL::text, p_filter text DEFAULT 'all'::text, p_sort text DEFAULT 'new'::text, p_limit integer DEFAULT 50, p_offset integer DEFAULT 0) RETURNS TABLE(id uuid, email text, status text, created_at timestamp with time zone, last_seen_at timestamp with time zone, sent_total bigint, sent_24h bigint, sent_30d bigint, used bigint, failed_total bigint, last_sent_at timestamp with time zone, auto_enabled boolean, auto_daily_limit integer, gmail_status text, has_cv boolean, pro_active boolean, pro_starts_at timestamp with time zone, pro_ends_at timestamp with time zone, free_emails integer, unlimited boolean, daily_limit integer, daily_unlimited boolean, note text, total_count bigint)
    LANGUAGE sql STABLE
    SET search_path TO 'pg_catalog', 'public', 'pg_temp'
    AS $$
    WITH stats AS (
        SELECT a.user_id,
               count(*) FILTER (WHERE a.status = 'sent') AS sent_total,
               count(*) FILTER (WHERE a.status = 'sent' AND a.sent_at > now() - interval '24 hours') AS sent_24h,
               count(*) FILTER (WHERE a.status = 'sent' AND a.sent_at > now() - interval '30 days') AS sent_30d,
               count(*) FILTER (WHERE a.status IN ('sent', 'sending')) AS used,
               count(*) FILTER (WHERE a.status = 'failed') AS failed_total,
               max(a.sent_at) AS last_sent_at
        FROM applications a WHERE a.method = 'email' GROUP BY a.user_id
    ),
    people AS (
        SELECT u.id, u.email, u.status, u.created_at, u.last_seen_at,
               coalesce(st.sent_total, 0) AS sent_total, coalesce(st.sent_24h, 0) AS sent_24h,
               coalesce(st.sent_30d, 0) AS sent_30d, coalesce(st.used, 0) AS used,
               coalesce(st.failed_total, 0) AS failed_total, st.last_sent_at,
               coalesce(x.enabled, false) AS auto_enabled, x.daily_limit AS auto_daily_limit,
               m.status AS gmail_status, (c.user_id IS NOT NULL) AS has_cv,
               (sub.email IS NOT NULL AND sub.starts_at <= now()
                    AND (sub.ends_at IS NULL OR sub.ends_at > now())) AS pro_active,
               sub.starts_at AS pro_starts_at, sub.ends_at AS pro_ends_at,
               l.free_emails, coalesce(l.unlimited, false) AS unlimited, l.daily_limit,
               coalesce(l.daily_unlimited, false) AS daily_unlimited, l.note
        FROM app_users u
        LEFT JOIN stats st ON st.user_id = u.id
        LEFT JOIN auto_apply x ON x.user_id = u.id
        LEFT JOIN mail_accounts m ON m.user_id = u.id
        LEFT JOIN user_cvs c ON c.user_id = u.id
        LEFT JOIN subscriptions sub ON sub.email = plan_email(u.email)
        LEFT JOIN user_limits l ON l.user_id = u.id
        WHERE coalesce(btrim(p_search), '') = ''
           OR u.email ILIKE '%' || replace(replace(replace(btrim(p_search), '\', '\\'), '%', '\%'), '_', '\_') || '%'
           OR u.id::text = lower(btrim(p_search))
    ),
    chosen AS (
        SELECT p.* FROM people p
        WHERE CASE coalesce(p_filter, 'all')
            WHEN 'pro' THEN p.pro_active OR p.unlimited
            WHEN 'free' THEN NOT (p.pro_active OR p.unlimited)
            WHEN 'auto' THEN p.auto_enabled
            WHEN 'custom' THEN p.free_emails IS NOT NULL OR p.unlimited OR p.daily_limit IS NOT NULL
                               OR p.daily_unlimited
            WHEN 'active' THEN p.last_seen_at > now() - interval '7 days'
            WHEN 'new' THEN p.created_at > now() - interval '7 days'
            WHEN 'sending' THEN p.sent_30d > 0
            WHEN 'blocked' THEN p.status = 'blocked'
            ELSE true
        END
    )
    SELECT ch.id, ch.email, ch.status, ch.created_at, ch.last_seen_at, ch.sent_total, ch.sent_24h, ch.sent_30d,
           ch.used, ch.failed_total, ch.last_sent_at, ch.auto_enabled, ch.auto_daily_limit, ch.gmail_status,
           ch.has_cv, ch.pro_active, ch.pro_starts_at, ch.pro_ends_at, ch.free_emails, ch.unlimited,
           ch.daily_limit, ch.daily_unlimited, ch.note, count(*) OVER () AS total_count
    FROM chosen ch
    ORDER BY
        CASE WHEN p_sort = 'sent' THEN ch.sent_total END DESC NULLS LAST,
        CASE WHEN p_sort = 'sent_24h' THEN ch.sent_24h END DESC NULLS LAST,
        CASE WHEN p_sort = 'seen' THEN ch.last_seen_at END DESC NULLS LAST,
        CASE WHEN p_sort = 'email' THEN lower(ch.email) END ASC NULLS LAST,
        ch.created_at DESC, ch.id
    LIMIT least(greatest(coalesce(p_limit, 50), 1), 200) OFFSET greatest(coalesce(p_offset, 0), 0);
$$;

CREATE FUNCTION public.api_hit(p_bucket text, p_window_seconds integer, p_max_hits integer) RETURNS integer
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public', 'pg_temp'
    AS $$
DECLARE
    v_now   double precision := extract(epoch FROM clock_timestamp());
    v_start double precision := floor(v_now / p_window_seconds) * p_window_seconds;
    v_hits  integer;
BEGIN
    INSERT INTO api_rate_limits AS r (bucket, window_start, hits)
    VALUES (p_bucket, to_timestamp(v_start), 1)
    ON CONFLICT (bucket, window_start) DO UPDATE SET hits = r.hits + 1
    RETURNING r.hits INTO v_hits;


    IF v_hits <= p_max_hits THEN
        RETURN 0;
    END IF;
    RETURN GREATEST(1, ceil(v_start + p_window_seconds - v_now)::integer);
END;
$$;

