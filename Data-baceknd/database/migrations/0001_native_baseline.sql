CREATE VIEW public.user_plans WITH (security_invoker='true') AS
 SELECT u.email,
        CASE
            WHEN ((s.email IS NOT NULL) AND (s.starts_at <= now()) AND ((s.ends_at IS NULL) OR (s.ends_at > now()))) THEN 'pro'::text
            ELSE 'free'::text
        END AS plan,
    s.ends_at AS pro_until,
    ( SELECT count(*) AS count
           FROM public.applications a
          WHERE ((a.user_id = u.id) AND (a.method = 'email'::text) AND (a.status = ANY (ARRAY['sent'::text, 'sending'::text])))) AS emails_sent,
    u.created_at AS joined_at,
    u.last_seen_at
   FROM (public.app_users u
     LEFT JOIN public.subscriptions s ON ((s.email = regexp_replace(lower(u.email), '@googlemail\.com$'::text, '@gmail.com'::text))))
  ORDER BY u.created_at DESC;

